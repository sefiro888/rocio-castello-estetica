def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for n, (a, b) in PARES.items():
        im = Image.open(FB / f"{n[2:]}.jpg" if n.startswith("fb") else POSTS / f"{n}.jpg").convert("RGB")
        w = min(a[2] - a[0], b[2] - b[0]) - 14
        h = min(a[3] - a[1], b[3] - b[1]) - 14
        for caja, suf in ((a, "a"), (b, "d")):
            cx, cy = (caja[0] + caja[2]) // 2, (caja[1] + caja[3]) // 2
            rec = im.crop((cx - w // 2, cy - h // 2, cx - w // 2 + w, cy - h // 2 + h))
            if rec.width < 900:
                rec = rec.resize((900, round(900 * rec.height / rec.width)), Image.LANCZOS)
            rec.save(OUT / f"{n}-{suf}.webp", "WEBP", quality=84)
        print(n, (w, h))


if __name__ == "__main__":
    main()
